// Writes the filled Tabler icons (MIT, tabler.io/icons) into the app, so nothing is fetched at run time:
//   npm pack @tabler/icons@<version> && tar -xzf tabler-icons-<version>.tgz
//   node avatar/tools/tabler-icons.mjs <the unpacked package/ folder>
// renderer/icons/tabler-filled.js: every filled icon, as its path data (live blocks: oct.icon);
// renderer/icons/chrome.js: the few the panels' own buttons use (so a panel doesn't parse all of them);
// renderer/icons/LICENSE-tabler.txt: the licence, which has to go with them.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// The panels' own buttons and marks, by what they're for (panel.js, player.js, film.js).
export const CHROME = {
  star: 'sparkles', // the title's star
  pen: 'pencil',
  clear: 'backspace', // wipe the ink
  pin: 'pin',
  pinned: 'pinned',
  close: 'square-rounded-x',
  open: 'external-link', // a picture's or page's source, in their browser
  play: 'player-play',
  pause: 'player-pause',
  back: 'player-track-prev',
  next: 'player-track-next',
  replay: 'player-skip-back',
  earlier: 'caret-left',
  later: 'caret-right',
  sent: 'circle-check',
};

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, '..', 'renderer', 'icons');

function main() {
  const pkg = process.argv[2];
  if (!pkg) throw new Error('usage: node avatar/tools/tabler-icons.mjs <unpacked @tabler/icons package folder>');
  const meta = JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8'));
  const nodes = JSON.parse(fs.readFileSync(path.join(pkg, 'tabler-nodes-filled.json'), 'utf8'));
  const icons = {};
  for (const [name, parts] of Object.entries(nodes).sort(([a], [b]) => a.localeCompare(b))) {
    if (!/^[a-z0-9-]+$/.test(name)) continue;
    const paths = parts.filter(([tag, attrs]) => tag === 'path' && typeof attrs.d === 'string' && attrs.fill !== 'none').map(([, attrs]) => attrs.d);
    if (paths.length) icons[name] = paths;
  }
  for (const name of Object.values(CHROME)) if (!icons[name]) throw new Error(`no filled icon "${name}" in ${meta.version}`);
  const head = `// Generated by avatar/tools/tabler-icons.mjs from @tabler/icons ${meta.version} (MIT, see LICENSE-tabler.txt). Do not edit.\n`;
  fs.mkdirSync(out, { recursive: true });
  const lines = Object.entries(icons).map(([name, paths]) => `  ${JSON.stringify(name)}: ${JSON.stringify(paths)},`);
  fs.writeFileSync(path.join(out, 'tabler-filled.js'), `${head}// Every filled icon: name -> the d of each of its paths (a 24 x 24 box, filled).\nexport const ICONS = {\n${lines.join('\n')}\n};\n`);
  const chrome = Object.entries(CHROME).map(([use, name]) => `  ${use}: ${JSON.stringify(icons[name])}, // ${name}`);
  fs.writeFileSync(path.join(out, 'chrome.js'), `${head}// The panels' own buttons and marks, by what they're for.\nexport const CHROME = {\n${chrome.join('\n')}\n};\n`);
  fs.copyFileSync(path.join(pkg, 'LICENSE'), path.join(out, 'LICENSE-tabler.txt'));
  console.log(`${Object.keys(icons).length} filled icons from @tabler/icons ${meta.version}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
